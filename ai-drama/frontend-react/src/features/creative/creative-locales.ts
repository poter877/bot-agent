export type CreativeCopy = Record<keyof typeof copy, string>

export function useCreativeCopy(): CreativeCopy {
  const locale = useUiLocale()
  const index = { zh: 0, en: 1, ja: 2, ko: 3 }[locale]
  return Object.fromEntries(Object.entries(copy).map(([key, values]) => [key, values[index]])) as CreativeCopy
}
